#!/usr/bin/env python3
"""Generate deterministic Markdown projections from repository authority."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = "governance/DOCUMENTATION_REGISTRY.json"


def _load(root: Path, path: str) -> dict:
    return json.loads((root / path).read_text(encoding="utf-8"))


def _index(items: list[dict], key: str = "id") -> dict[str, dict]:
    return {str(item[key]): item for item in items}


def _render_project_status(root: Path, registry: dict) -> str:
    capabilities = _index(_load(root, "governance/CAPABILITY_MAP.json")["capabilities"])
    technologies = _index(_load(root, "governance/TECHNOLOGY_REGISTRY.json")["technologies"])
    lines = [
        "# Project status projection",
        "",
        "<!-- GENERATED by scripts/docs_generate.py. Do not edit by hand. -->",
        "",
        "This is a replaceable offline projection of repository authorities, not an execution or release authority.",
        "",
        "- Lifecycle authority: `governance/CAPABILITY_MAP.json`.",
        "- Technology authority: `governance/TECHNOLOGY_REGISTRY.json`.",
        "- Planned slice scope: `docs/roadmap/VERTICAL_SLICES.md`.",
        "- Execution, CI and deployment evidence: query live GitHub/provider records; intentionally not cached here.",
        "",
        "## Capabilities",
        "",
        "| Capability | Status |",
        "| --- | --- |",
    ]
    for capability_id in registry["projections"]["capabilities"]:
        item = capabilities[capability_id]
        lines.append(f"| `{capability_id}` | `{item['status']}` |")
    lines.extend([
        "",
        "## Technologies",
        "",
        "| Technology | Status |",
        "| --- | --- |",
    ])
    for technology_id in registry["projections"]["technologies"]:
        item = technologies[technology_id]
        lines.append(f"| `{technology_id}` | `{item['status']}` |")
    lines.extend([
        "",
        "Do not infer active work, CI health or production deployment from this file.",
        "",
    ])
    return "\n".join(lines)


GENERATORS = {
    "project_status_projection": _render_project_status,
}


def render_outputs(root: Path = ROOT) -> dict[str, str]:
    registry = _load(root, REGISTRY_PATH)
    outputs: dict[str, str] = {}
    for document in registry["documents"]:
        if document["mode"] != "generated":
            continue
        generator = GENERATORS[document["generator"]]
        outputs[document["path"]] = generator(root, registry)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if committed generated docs differ")
    args = parser.parse_args()

    stale: list[str] = []
    for relative, content in render_outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated {relative}")

    if stale:
        print("Documentation generation check failed. Regenerate:")
        print("  python3 scripts/docs_generate.py")
        for path in stale:
            print(f"- stale: {path}")
        return 1
    if args.check:
        print("Generated documentation is current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
