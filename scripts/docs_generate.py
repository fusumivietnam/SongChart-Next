#!/usr/bin/env python3
"""Generate deterministic Markdown projections from repository authority."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = "governance/DOCUMENTATION_REGISTRY.json"


def _load(root: Path, path: str) -> dict:
    return json.loads((root / path).read_text(encoding="utf-8"))


def _index(items: list[dict], key: str = "id") -> dict[str, dict]:
    return {str(item[key]): item for item in items}


def _render_capabilities(root: Path, registry: dict) -> str:
    authority = _load(root, "governance/CAPABILITY_MAP.json")
    by_id = _index(authority["capabilities"])
    lines = [
        "# Capability status projection",
        "",
        "<!-- GENERATED by scripts/docs_generate.py. Do not edit by hand. -->",
        "",
        "Authority: `governance/CAPABILITY_MAP.json`.",
        "",
        "| Capability | Status |",
        "| --- | --- |",
    ]
    for capability_id in registry["projections"]["capabilities"]:
        item = by_id[capability_id]
        lines.append(f"| `{capability_id}` | `{item['status']}` |")
    lines.extend(["", "This file is a replaceable projection, not lifecycle authority.", ""])
    return "\n".join(lines)


def _render_technologies(root: Path, registry: dict) -> str:
    authority = _load(root, "governance/TECHNOLOGY_REGISTRY.json")
    by_id = _index(authority["technologies"])
    lines = [
        "# Technology status projection",
        "",
        "<!-- GENERATED by scripts/docs_generate.py. Do not edit by hand. -->",
        "",
        "Authority: `governance/TECHNOLOGY_REGISTRY.json`.",
        "",
        "| Technology | Status |",
        "| --- | --- |",
    ]
    for technology_id in registry["projections"]["technologies"]:
        item = by_id[technology_id]
        lines.append(f"| `{technology_id}` | `{item['status']}` |")
    lines.extend(["", "This file is a replaceable projection, not technology authority.", ""])
    return "\n".join(lines)


GENERATORS = {
    "capability_projection": _render_capabilities,
    "technology_projection": _render_technologies,
}


def render_outputs(root: Path = ROOT) -> dict[str, str]:
    registry = _load(root, REGISTRY_PATH)
    outputs: dict[str, str] = {}
    for document in registry["documents"]:
        if document["mode"] != "generated":
            continue
        generator = GENERATORS[document["generator"]]
        outputs[document["path"]] = generator(root, registry)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if committed generated docs differ")
    args = parser.parse_args()

    stale: list[str] = []
    for relative, content in render_outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated {relative}")

    if stale:
        print("Documentation generation check failed. Regenerate:")
        print("  python3 scripts/docs_generate.py")
        for path in stale:
            print(f"- stale: {path}")
        return 1
    if args.check:
        print("Generated documentation is current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
